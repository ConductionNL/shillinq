<!--
 The `index` page type for shillinq: the library's index page, scoped to the
 active administration when the page's schema carries `administrationId`.

 CnPageRenderer hands this component exactly the props it would hand the
 library's index page, so every renderer wiring (row clicks, detail routes,
 saved views, actions) is kept. A page over a scoped schema
 (`src/administrationScopedPages.json`, generated by
 `scripts/generate-administration-scoped-pages.js`) gets `administrationId`
 added to its fixed `filter`, which the list applies on every fetch and the
 address cannot override. Other pages pass through unchanged.

 Stands in until nextcloud-vue resolves a `@context.<key>` sentinel in page
 config; the pages then declare the filter in the manifest and this wrapper
 is removed in the same change.

 @spec openspec/changes/ledger-multi-administration/specs/bookkeeping-multi-administratie/spec.md#requirement-lists-show-the-active-administration-only-req-lma-002
-->
<template>
	<ScopedIndexPage v-if="ready" v-bind="pageProps">
		<template v-for="(_, name) in $slots" #[name]="slotProps">
			<slot :name="name" v-bind="slotProps || {}" />
		</template>
	</ScopedIndexPage>
</template>

<script>
import { defaultPageTypes } from '@conduction/nextcloud-vue'
import axios from '@nextcloud/axios'
import { generateUrl } from '@nextcloud/router'
import scopedPages from '../administrationScopedPages.json'

/** The record field that names a record's administration. */
export const SCOPE_FIELD = 'administrationId'

const SCOPED_SCHEMAS = new Set(scopedPages.schemas)

/** The active administration, read once per page load: switching reloads the page. */
let activeAdministration = null

/**
 * Whether records of this schema carry `administrationId`.
 *
 * @param {unknown} schema The page's `schema` prop.
 * @return {boolean}
 */
export function isScopedSchema(schema) {
	return typeof schema === 'string' && SCOPED_SCHEMAS.has(schema)
}

/**
 * The active administration's id from the context endpoint, or '' when the
 * user has none or it cannot be read. A failed read is retried on the next
 * page.
 *
 * @return {Promise<string>}
 */
export function loadActiveAdministrationId() {
	if (activeAdministration === null) {
		activeAdministration = axios.get(generateUrl('/apps/shillinq/api/administrations/context'))
			.then((response) => String(response?.data?.activeAdministrationId || ''))
			.catch(() => {
				activeAdministration = null
				return ''
			})
	}
	return activeAdministration
}

/**
 * Forget the cached administration (tests).
 *
 * @return {void}
 */
export function resetActiveAdministration() {
	activeAdministration = null
}

/**
 * The index page's props with the administration added to its fixed filter.
 *
 * @param {object} attrs The props the renderer passed.
 * @param {string} administrationId The active administration, or ''.
 * @return {object} The props to render the index page with.
 */
export function scopedProps(attrs, administrationId) {
	if (!isScopedSchema(attrs.schema) || administrationId === '') {
		return attrs
	}
	const filter = (attrs.filter && typeof attrs.filter === 'object' && !Array.isArray(attrs.filter)) ? attrs.filter : {}
	return { ...attrs, filter: { ...filter, [SCOPE_FIELD]: administrationId } }
}

export default {
	name: 'AdministrationScopedIndex',

	components: {
		ScopedIndexPage: defaultPageTypes?.index,
	},

	inheritAttrs: false,

	data() {
		return {
			activeAdministrationId: '',
			loaded: false,
		}
	},

	computed: {
		/**
		 * Whether this page lists records of one administration.
		 *
		 * @return {boolean}
		 */
		scoped() {
			return isScopedSchema(this.$attrs.schema)
		},

		/**
		 * Render once the scope is known, so an unscoped list is never fetched first.
		 *
		 * @return {boolean}
		 */
		ready() {
			return this.scoped === false || this.loaded === true
		},

		/**
		 * The props the index page renders with.
		 *
		 * @return {object}
		 */
		pageProps() {
			return scopedProps(this.$attrs, this.activeAdministrationId)
		},
	},

	created() {
		if (this.scoped) {
			this.loadScope()
		}
	},

	methods: {
		/**
		 * Read the active administration, then render the list.
		 *
		 * @return {Promise<void>}
		 */
		async loadScope() {
			this.activeAdministrationId = await loadActiveAdministrationId()
			this.loaded = true
		},
	},
}
</script>
