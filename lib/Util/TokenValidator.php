/**
 * Confirmation token validator.
 *
 * Pure helper used by ConfirmationApiController and ConfirmationTokenService
 * to generate, hash and validate 32-character URL-safe confirmation tokens
 * for the appointment confirmation flow per REQ-BCF-002/004.
 *
 * Tokens are stored as salted bcrypt hashes (cost 12) — never plaintext.
 * Validation uses PHP's password_verify which is constant-time, so callers
 * cannot leak token bytes through timing side channels.
 *
 * @category Util
 * @package  OCA\Shillinq\Util
